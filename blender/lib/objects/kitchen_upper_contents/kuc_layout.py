CELL = 128
SIZE = 1024


def _regions():
    regions = {"palette": (0, 0, 256, 256)}
    cells = [(cx, cy) for cy in range(SIZE // CELL) for cx in range(SIZE // CELL)
             if not (cx < 2 and cy < 2)]
    if len(LABEL_NAMES) > len(cells):
        raise ValueError("too many labels for the atlas")
    for name, (cx, cy) in zip(LABEL_NAMES, cells):
        regions[name] = (cx * CELL, cy * CELL, CELL, CELL)
    return regions


ATLAS = {"name": NAME, "size": SIZE, "regions": _regions()}


def pal_px(name):
    """Pixel centre of a palette swatch (8 x 8 swatches of 32 px)."""
    i = PAL_NAMES.index(name)
    return 32 * (i % 8) + 16, 32 * (i // 8) + 16
